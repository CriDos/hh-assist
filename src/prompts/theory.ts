// System prompt for single-answer certification tests. The model first breaks
// down the question and options, writes the reasoning, and only AFTER it gives
// the final answer as a strict «Ответ: <номер>» line — the parser
// (parseAnswerResponse in builder.js) takes the LAST «Ответ: N» line,
// so the reasoning never confuses the parse.
export const DEFAULT_SYSTEM = [
  'Ты решаешь сложный сертификационный тест: дан вопрос и пронумерованные варианты ответа.',
  'Выбери ОДИН правильный вариант.',
  '',
  'Сначала тщательно проанализируй вопрос и все варианты: пройдись по каждому, отбрось заведомо неверные, объясни, почему выбранный вариант правильный.',
  '',
  'Ответ оформи ровно в две строки, без лишнего:',
  'Обоснование: <краткое обоснование, 2–4 предложения>',
  'Ответ: <номер>',
  'Например:',
  'Обоснование: Варианты 1 и 3 не подходят, потому что…; вариант 2 верный, так как…',
  'Ответ: 2',
  '',
  'Формат строки «Ответ: N» менять нельзя — по ней засчитывается ответ. Обоснование пиши на своей строке строго перед ней; после «Ответ: N» ничего не добавляй (без markdown-разметки и пояснений).'
].join('\n');

// Same, for questions with several correct answers (subType MULTIPLE).
export const MULTIPLE_SYSTEM = [
  'Ты решаешь сложный сертификационный тест: дан вопрос и пронумерованные варианты ответа.',
  'Выбери ВСЕ правильные варианты (их может быть два и больше).',
  '',
  'Сначала тщательно проанализируй вопрос и все варианты: пройдись по каждому, отбрось заведомо неверные, объясни, почему выбранные варианты правильные.',
  '',
  'Ответ оформи ровно в две строки, без лишнего:',
  'Обоснование: <краткое обоснование, 2–4 предложения>',
  'Ответ: <номер1,номер2>',
  'Например:',
  'Обоснование: Подходят варианты 1 и 3, так как…; вариант 2 содержит ошибку…',
  'Ответ: 1,3',
  '',
  'Если сомневаешься в варианте — не включай его: лучше выбрать меньше, чем ошибиться.',
  'Формат строки «Ответ: N» менять нельзя — по ней засчитывается ответ. Обоснование пиши на своей строке строго перед ней; после «Ответ: N» ничего не добавляй (без markdown-разметки и пояснений).'
].join('\n');

export function buildTheoryMessages(
  config: { systemPrompt?: string },
  question: { subType?: string; question: string }
) {
  const system =
    config.systemPrompt || (question.subType === 'MULTIPLE' ? MULTIPLE_SYSTEM : DEFAULT_SYSTEM);
  return {
    system,
    user: question.question
  };
}
